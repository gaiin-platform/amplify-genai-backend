@required_env_vars({
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.PUT_OBJECT],
    "CONVERSATION_METADATA_TABLE": [DynamoDBOperation.PUT_ITEM],
    # "S3_CONVERSATIONS_BUCKET_NAME": [S3Operation.PUT_OBJECT], #Marked for deletion
})
@validated("conversation_upload")
def register_conversation(event, context, current_user, name, data):
    data = data["data"]

    prepMessages = data["messages"]

    for message in prepMessages:
        message["id"] = str(uuid.uuid4())
        message["type"] = "chat"

    current_utc_time = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    supplied_id = data.get("id")
    if supplied_id is None:
        supplied_id = str(uuid.uuid4())
    elif not is_valid_conversation_id(supplied_id):
        return {"success": False, "reason": "INVALID_ID", "message": "Invalid conversation id"}

    conversation = {
        "id": supplied_id,
        "name": data["name"],
        "messages": prepMessages,
        "folderId": "agents",
        "tags": data.get("tags", []),
        "data": data.get("data", {}),
        "date": data.get("date", data.get("date", current_utc_time)),
        "isLocal": False,
    }

    compressed_conversation = lzw_compress(json.dumps(conversation))

    conversation_key = f"{current_user}/{conversation['id']}"
    return upload_to_s3(conversation_key, compressed_conversation, None)

@required_env_vars({
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.GET_OBJECT],
    # "S3_CONVERSATIONS_BUCKET_NAME": [S3Operation.GET_OBJECT], #Marked for deletion
})
@validated("read")
def get_conversation(event, context, current_user, name, data):
    query_param = get_conversation_query_param(event.get("queryStringParameters", {}))
    if not query_param["success"]:
        return query_param["response"]

    conversation_id = query_param["query_value"]
    s3 = boto3.client("s3")
    consolidation_bucket = os.environ["S3_CONSOLIDATION_BUCKET_NAME"]
    conversations_bucket = os.environ.get("S3_CONVERSATIONS_BUCKET_NAME")  # Legacy bucket

    # Try consolidation bucket first (new format)
    consolidation_key = f"conversations/{current_user}/{conversation_id}"
    
    try:
        response = s3.get_object(Bucket=consolidation_bucket, Key=consolidation_key)
        conversation_body = response["Body"].read().decode("utf-8")
        conversation_data = json.loads(conversation_body)
        return {
            "success": True,
            "conversation": conversation_data["conversation"],
            # lets the client detect a concurrent modification when it saves back
            "version": int(response["LastModified"].timestamp() * 1000),
        }
    except (BotoCoreError, ClientError) as e:
        if getattr(e, "response", {}).get("Error", {}).get("Code") != "NoSuchKey":
            logger.error("Unexpected error accessing consolidation bucket: %s", str(e))
            return {
                "success": False,
                "message": "Failed to retrieve conversation from consolidation bucket",
                "error": str(e),
            }

    # Fallback to legacy bucket if not found in consolidation bucket
    if conversations_bucket:
        legacy_key = f"{current_user}/{conversation_id}"
        try:
            response = s3.get_object(Bucket=conversations_bucket, Key=legacy_key)
            conversation_body = response["Body"].read().decode("utf-8")
            conversation_data = json.loads(conversation_body)
            return {
                "success": True,
                "conversation": conversation_data["conversation"],
                "version": int(response["LastModified"].timestamp() * 1000),
            }
        except (BotoCoreError, ClientError) as e:
            logger.debug("Conversation not found in legacy bucket either: %s", str(e))

    # Conversation not found in either bucket
    return {
        "success": False,
        "message": "Conversation not found",
        "error": "NoSuchKey",
        "type": "NoSuchKey"
    }


def pick_conversation_attributes(conversation, include_timestamp=False):
    """Extract essential conversation attributes for metadata responses"""
    attributes = [
        "id",
        "name",
        "model",
        "folderId",
        "tags",
        "isLocal",
        "groupType",
        "codeInterpreterAssistantId",
        # sent by the frontend under this name; the list response used to drop both of these so every
        # sync stripped them from the local entry
        "codeInterpreterRecordId",
        "date",
    ]
    result = {attr: conversation.get(attr, None) for attr in attributes}

    # Add timestamp if requested
    if include_timestamp:
        result["lastModified"] = conversation.get(
            "lastModified", int(time.time() * 1000)
        )

    return result
@required_env_vars({
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT],
    # "S3_CONVERSATIONS_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT], #Marked for deletion
})
@validated("read")
def get_all_conversations(event, context, current_user, name, data):
    # Check for days query parameter
    query_params = event.get("queryStringParameters", {}) or {}
    days_param = query_params.get("days")
    days = None
    
    if days_param:
        try:
            days_value = int(days_param)
            # If days is 0 or negative, treat as "get all" (days = None)
            if days_value > 0:
                days = days_value
        except ValueError:
            return {"success": False, "message": "Days parameter must be a valid number"}
    
    conversations, truncated = get_all_complete_conversations_ex(current_user, days)
    if conversations is None:
        return {"success": False, "message": "Failed to retrieve conversations from S3"}
    elif len(conversations) == 0:
        response = {"success": True, "message": "No conversations saved to S3"}
        if truncated:
            response["truncated"] = True
        return response

    summaries = []
    for item in conversations:
        full = item.get("conversation") if isinstance(item, dict) else None
        if not isinstance(full, dict):
            continue
        summary = pick_conversation_attributes(full)
        # Lets the client tell a real (but stripped) chat from an untouched placeholder without
        # downloading it: 0 = empty, otherwise the number of messages (1 if only the
        # compressed form is stored).
        summary["messageCount"] = len(full.get("messages") or []) or (1 if full.get("compressedMessages") else 0)
        item["conversation"] = summary
        summaries.append(item)

    presigned_urls = get_presigned_urls(current_user, summaries)
    response = {"success": True, "presignedUrls": presigned_urls}
    if truncated:
        # the time budget cut the listing short (newest conversations come first); the client must
        # not treat this as the complete set
        response["truncated"] = True
    return response
@required_env_vars({
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT],
    # "S3_CONVERSATIONS_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT], #Marked for deletion
})
@validated("read")
def get_empty_conversations(event, context, current_user, name, data):
    conversations, truncated = get_all_complete_conversations_ex(current_user)
    if conversations is None:
        return {"success": False, "message": "Failed to retrieve conversations from S3"}
    if truncated:
        # Never report "empty" chats from a partial listing: the client deletes based on this.
        return {"success": False, "message": "Too many conversations to scan at once", "truncated": True}
    if len(conversations) == 0:
        return {"success": True, "message": "No conversations saved to S3"}

    empty_conversations = []
    nonempty_conversations_ids = []
    for item in conversations:
        conv = item.get("conversation") if isinstance(item, dict) else None
        if not isinstance(conv, dict):
            continue
        # compressedMessages counts as content: a stripped-form chat is not empty
        if not conversation_has_content(conv):
            empty_conversations.append(pick_conversation_attributes(conv))
        elif conv.get("id"):
            nonempty_conversations_ids.append(conv["id"])

    presigned_urls = get_presigned_urls(current_user, empty_conversations)
    return {
        "success": True,
        "presignedUrls": presigned_urls,
        "nonEmptyIds": nonempty_conversations_ids,
    }


def collect_conversation_objects(s3, current_user):
    """List every stored conversation object for the user across both buckets, one entry per
    conversation id. The consolidation bucket wins over the legacy bucket (all writes go to
    consolidation, so a legacy copy is always stale).

    Raises on a consolidation-bucket listing failure: returning a partial list would look like a
    successful, complete sync to the client. A legacy-bucket failure is tolerated (it is being
    retired), but logged.
    """
    consolidation_bucket = os.environ["S3_CONSOLIDATION_BUCKET_NAME"]
    conversations_bucket = os.environ.get("S3_CONVERSATIONS_BUCKET_NAME")  # Legacy bucket

    by_id = {}
    if conversations_bucket:
        try:
            for obj in list_all_objects(s3, conversations_bucket, f"{current_user}/"):
                obj["_bucket"] = conversations_bucket
                by_id[obj["Key"].split("/")[-1]] = obj
        except (BotoCoreError, ClientError) as e:
            logger.error("Error accessing legacy bucket: %s", str(e))

    consolidation_count = 0
    for obj in list_all_objects(s3, consolidation_bucket, f"conversations/{current_user}/"):
        obj["_bucket"] = consolidation_bucket
        by_id[obj["Key"].split("/")[-1]] = obj  # overrides a legacy entry with the same id
        consolidation_count += 1
    logger.info("Found %d conversations in consolidation bucket, %d total after de-duplication",
                consolidation_count, len(by_id))
    return list(by_id.values())


# Default wall-clock budget for downloading a user's conversations. The Lambda timeout is 30s and API
# Gateway cuts the request at 29s, so stop early and return what we have (flagged as truncated).
_DEFAULT_LISTING_BUDGET_SECONDS = 20

_monotonic = time.monotonic  # indirection so tests can drive the clock


def get_all_complete_conversations_ex(current_user, days=None,
                                      time_budget_seconds=_DEFAULT_LISTING_BUDGET_SECONDS):
    """Download + decompress the user's conversations, newest first.

    Returns (conversations, truncated). conversations is None only if the listing itself failed. A
    single unreadable object is skipped (and logged) instead of failing the whole call. When the time
    budget runs out the conversations gathered so far are returned with truncated=True.
    """
    deadline = None if time_budget_seconds is None else _monotonic() + time_budget_seconds
    s3 = boto3.client("s3")

    try:
        all_objects = collect_conversation_objects(s3, current_user)
    except (BotoCoreError, ClientError) as e:
        logger.error("Error listing conversations: %s", str(e))
        return None, False

    if days is not None:
        cutoff_date = datetime.now(timezone.utc) - timedelta(days=days)
        logger.debug("Filtering conversations newer than: %s", cutoff_date)
        all_objects = [obj for obj in all_objects if obj["LastModified"] >= cutoff_date]

    # newest first, so a truncated result still contains the chats the user most likely cares about
    all_objects.sort(key=lambda obj: obj["LastModified"], reverse=True)

    def load(obj):
        try:
            response = s3.get_object(Bucket=obj["_bucket"], Key=obj["Key"])
            body = json.loads(response["Body"].read().decode("utf-8"))
            uncompressed = lzw_uncompress(body["conversation"])
            if isinstance(uncompressed, dict) and uncompressed:
                return {"conversation": uncompressed, "folder": body.get("folder")}
            logger.warning("Skipping conversation %s: payload is not a conversation object", obj["Key"])
        except Exception as e:  # corrupt json / lzw ValueError / missing keys / S3 errors
            logger.error("Skipping unreadable conversation %s: %s", obj["Key"], str(e))
        return None

    conversations = []
    truncated = False
    pool = ThreadPoolExecutor(max_workers=_S3_FETCH_WORKERS)
    try:
        futures = [pool.submit(load, obj) for obj in all_objects]
        for future in futures:
            if not truncated:
                remaining = None if deadline is None else deadline - _monotonic()
                if remaining is not None and remaining <= 0 and not future.done():
                    truncated = True
                else:
                    try:
                        result = future.result(timeout=remaining)
                    except FutureTimeoutError:
                        truncated = True
                    else:
                        if result:
                            conversations.append(result)
                        continue
            # past the deadline: keep only work that already finished
            if future.done() and not future.cancelled():
                result = future.result()
                if result:
                    conversations.append(result)
    finally:
        # do not wait for in-flight downloads: return promptly, drop everything still queued
        pool.shutdown(wait=False, cancel_futures=True)

    if truncated:
        logger.warning("Listing truncated by time budget: returning %d of %d conversations",
                       len(conversations), len(all_objects))
    logger.info("Successfully retrieved %d of %d conversations", len(conversations), len(all_objects))
    return conversations, truncated


