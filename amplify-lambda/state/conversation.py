# Conversation ids are generated by the client (uuid v4) but imported / agent-registered chats may
# carry other ids (e.g. containing ':', '.', '@', '='). Accept any safe token so those chats can still
# be fetched and deleted, while rejecting anything that could alter the S3 key layout: no '/', no
# whitespace / control characters, and not the path segments "." and "..".
_CONVERSATION_ID_RE = re.compile(r"[A-Za-z0-9_.:@=+\-]{1,256}")

# Concurrency used when downloading many conversation objects in one request.
_S3_FETCH_WORKERS = 16


def is_valid_conversation_id(conversation_id):
    return (
        isinstance(conversation_id, str)
        and conversation_id not in (".", "..")
        and bool(_CONVERSATION_ID_RE.fullmatch(conversation_id))
    )


def list_all_objects(s3, bucket, prefix):
    """List every object under a prefix. A single list_objects_v2 call stops at 1000 keys, which
    silently hid chats for large accounts (keys are random uuids, so the cut-off was arbitrary)."""
    objects = []
    paginator = s3.get_paginator("list_objects_v2")
    for page in paginator.paginate(Bucket=bucket, Prefix=prefix):
        objects.extend(page.get("Contents", []))
    return objects


def object_version_ms(s3, bucket, key):
    """Version of a stored conversation = S3 LastModified in epoch ms (None if it does not exist).
    Works for every write path, including presigned uploads that bypass this lambda."""
    try:
        head = s3.head_object(Bucket=bucket, Key=key)
        return int(head["LastModified"].timestamp() * 1000)
    except ClientError as e:
        if e.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
            return None
        raise


def conversation_has_content(conversation):
    if not isinstance(conversation, dict):
        return False
    return bool(conversation.get("messages")) or bool(conversation.get("compressedMessages"))


def read_stored_conversation(s3, bucket, key):
    """Return the decompressed conversation stored at key, or None when missing/unreadable."""
    try:
        response = s3.get_object(Bucket=bucket, Key=key)
        body = json.loads(response["Body"].read().decode("utf-8"))
        return lzw_uncompress(body["conversation"]) or None
    except ClientError as e:
        if e.response.get("Error", {}).get("Code") == "NoSuchKey":
            return None
        raise
    except (ValueError, KeyError, TypeError):
        return None


def update_conversation_cache(user_id, conversation_data, folder=None):
    """Update conversation metadata cache when conversation changes"""
    try:
        if not os.environ.get("CONVERSATION_METADATA_TABLE"):
            return  # Cache not available

        dynamodb = boto3.resource("dynamodb")
        table = dynamodb.Table(os.environ.get("CONVERSATION_METADATA_TABLE"))

        # Extract metadata from conversation
        metadata = pick_conversation_attributes(
            conversation_data, include_timestamp=True
        )

        item = {
            "user_id": user_id,
            "conversation_id": metadata.get("id", ""),
            "name": metadata.get("name", ""),
            "model": metadata.get("model", ""),
            "folder_id": metadata.get("folderId"),
            "tags": metadata.get("tags", []),
            "is_local": metadata.get("isLocal", False),
            "group_type": metadata.get("groupType"),
            "code_interpreter_assistant_id": metadata.get(
                "codeInterpreterAssistantId"
            ),
            "last_modified": int(
                time.time() * 1000
            ),  # Use current timestamp for uploads
            "s3_key": f"{user_id}/{metadata.get('id', '')}",
            "folder_name": folder.get("name") if folder else None,
            "updated_at": int(time.time() * 1000),
        }
        
        # Convert any float values to Decimal for DynamoDB compatibility
        item = convert_floats_to_decimal(item)
        
        table.put_item(Item=item)

        logger.debug("Updated cache for conversation %s", metadata.get('id', ''))

    except Exception as e:
        logger.warning("Failed to update conversation cache (non-blocking): %s", str(e))


def upload_to_s3(key, conversation, folder=None):
    s3 = boto3.client("s3")
    # Use consolidation bucket for new conversations
    consolidation_bucket = os.environ["S3_CONSOLIDATION_BUCKET_NAME"]
    
    # Convert legacy key format to consolidation bucket format
    if "/" in key:
        user_id, conversation_id = key.split("/", 1)
        consolidation_key = f"conversations/{user_id}/{conversation_id}"
    else:
        consolidation_key = f"conversations/{key}"

    try:
        s3.put_object(
            Bucket=consolidation_bucket,
            Key=consolidation_key,
            Body=json.dumps({"conversation": conversation, "folder": folder}),
        )
        logger.info("Successfully uploaded conversation to consolidation bucket: %s", consolidation_key)
        return {"success": True, "message": "Successfully uploaded conversation to consolidation bucket"}
    except (BotoCoreError, ClientError) as e:
        logger.error("Error: %s", str(e))
        return {
            "success": False,
            "message": "Failed to upload conversation to consolidation bucket",
            "error": str(e),
        }
def check_upload_allowed(s3, key, expected_version, incoming_conversation=None):
    """Guards against overwriting newer / fuller data with a stale or empty copy.

    Returns None when the write may proceed, otherwise an error response dict.

    * expected_version: the version (S3 LastModified, ms) the client last saw. If the stored object
      has since been modified (another tab/device), the write is rejected with reason CONFLICT so
      the client can keep its copy as a separate chat instead of silently clobbering the other one.
      Omitted/None means "no baseline known" and the check is skipped (older clients, brand new chats).
      Known limitation: S3 LastModified has 1-second resolution, so two writes landing within the same
      second as the client's baseline are indistinguishable and the later one is not flagged. A
      non-integer expected_version is rejected with reason INVALID_VERSION.
    * incoming_conversation: when it has no messages, refuse to replace a stored chat that has some
      (a stub / half-loaded conversation must never wipe the real one).
    """
    bucket = os.environ["S3_CONSOLIDATION_BUCKET_NAME"]
    if expected_version is not None:
        if isinstance(expected_version, bool):
            expected_version = None  # bool is an int subclass but never a valid version
        try:
            expected_version = int(expected_version)
        except (TypeError, ValueError, OverflowError):
            return {"success": False, "reason": "INVALID_VERSION", "message": "Invalid expectedVersion"}
    if expected_version is not None:
        try:
            current = object_version_ms(s3, bucket, key)
        except (BotoCoreError, ClientError) as e:
            logger.error("Version check failed for %s: %s", key, str(e))
            return {"success": False, "reason": "VERSION_CHECK_FAILED",
                    "message": "Could not verify the stored version of this conversation"}
        if current is not None and current > expected_version:
            return {"success": False, "reason": "CONFLICT", "version": current,
                    "message": "Conversation was modified elsewhere since it was loaded"}

    if incoming_conversation is not None and not conversation_has_content(incoming_conversation):
        try:
            existing = read_stored_conversation(s3, bucket, key)
        except (BotoCoreError, ClientError) as e:
            logger.error("Empty-overwrite check failed for %s: %s", key, str(e))
            return {"success": False, "reason": "VERSION_CHECK_FAILED",
                    "message": "Could not verify the stored conversation"}
        if conversation_has_content(existing):
            logger.warning("Refusing to overwrite non-empty conversation %s with an empty one", key)
            return {"success": False, "reason": "EMPTY_OVERWRITE",
                    "message": "Refusing to replace a conversation that has messages with an empty one"}
    return None


@required_env_vars({
    "CONVERSATION_METADATA_TABLE": [DynamoDBOperation.PUT_ITEM],
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT],
    # "S3_CONVERSATIONS_BUCKET_NAME": [S3Operation.PUT_OBJECT], #Marked for deletion
})
@validated("conversation_upload")
def upload_conversation(event, context, current_user, name, data):
    data = data["data"]
    conversation = data["conversation"]
    conversation_id = data["conversationId"]
    folder = data.get("folder", None)
    expected_version = data.get("expectedVersion", None)

    if not is_valid_conversation_id(conversation_id):
        return {"success": False, "reason": "INVALID_ID", "message": "Invalid conversationId"}

    conversation_key = f"{current_user}/{conversation_id}"
    consolidation_key = f"conversations/{conversation_key}"

    # An unreadable payload (cannot be decoded, or decodes to something other than a conversation
    # object, e.g. "" for an empty list) would be stored but then skipped by every listing, making the
    # chat invisible. Reject it instead so the client keeps its local copy and retries.
    try:
        decompressed_conversation = lzw_uncompress(conversation)
    except Exception as e:
        logger.warning("Rejecting unreadable conversation payload %s: %s", conversation_id, str(e))
        decompressed_conversation = None
    if not isinstance(decompressed_conversation, dict):
        return {"success": False, "reason": "INVALID_PAYLOAD",
                "message": "Conversation payload could not be read"}

    s3 = boto3.client("s3")
    rejection = check_upload_allowed(s3, consolidation_key, expected_version, decompressed_conversation)
    if rejection:
        return rejection

    result = upload_to_s3(conversation_key, conversation, folder)

    if result.get("success"):
        try:
            result["version"] = object_version_ms(
                s3, os.environ["S3_CONSOLIDATION_BUCKET_NAME"], consolidation_key
            )
        except Exception as e:
            logger.warning("Could not read back version for %s: %s", conversation_id, str(e))
        if decompressed_conversation:  # an empty dict is a valid payload but has nothing to cache
            update_conversation_cache(current_user, decompressed_conversation, folder)

    return result


@required_env_vars({
    "S3_CONSOLIDATION_BUCKET_NAME": [S3Operation.PUT_OBJECT, S3Operation.GET_OBJECT],
})
@validated("conversation_upload")
def get_conversation_upload_url(event, context, current_user, name, data):
    """Return a short-lived presigned S3 PUT URL so the frontend can upload a
    large conversation directly to S3, bypassing the API Gateway 10 MB limit.

    The object written by the client must have the same shape as upload_to_s3:
        { "conversation": <lzw-compressed number[]>, "folder": <folder|null> }
    All existing read paths work identically once the object is at the key.
    """
    query_params = event.get("queryStringParameters", {}) or {}
    conversation_id = query_params.get("conversationId", "")

    if not is_valid_conversation_id(conversation_id):
        return {"success": False, "message": "Invalid or missing conversationId"}

    consolidation_bucket = os.environ["S3_CONSOLIDATION_BUCKET_NAME"]
    s3 = boto3.client("s3")
    key = f"conversations/{current_user}/{conversation_id}"

    # The client PUTs straight to S3, so the conflict check can only happen here, when the URL is
    # issued. (The empty-overwrite guard cannot run for this path, the body is not seen.)
    expected_version = query_params.get("expectedVersion")
    if expected_version not in (None, "", "null", "undefined"):
        try:
            expected_version = int(expected_version)
        except ValueError:
            return {"success": False, "message": "Invalid expectedVersion"}
        rejection = check_upload_allowed(s3, key, expected_version)
        if rejection:
            return rejection

    try:
        presigned_url = s3.generate_presigned_url(
            "put_object",
            Params={
                "Bucket": consolidation_bucket,
                "Key": key,
                "ContentType": "application/json",
            },
            ExpiresIn=300,  # 5 minutes — plenty for any reasonable upload
        )
        logger.info("Generated presigned upload URL for conversation %s", conversation_id)
        return {"success": True, "presignedUrl": presigned_url}
    except (BotoCoreError, ClientError) as e:
        logger.error("Error generating presigned upload URL: %s", str(e))
        return {"success": False, "message": "Failed to generate presigned upload URL"}


